function task(k, v, max) {
  P.tasks.forEach(t => {
    const d = TASKS[t.i];
    if (d.k !== k || t.done)
      return;
    t.p = max ? Math.max(t.p, v) : t.p + v;
    if (t.p >= d.n) {
      t.p = d.n;
      t.done = true;
      addCoins(d.r);
      toast('Задание: ' + d.t + ' +' + d.r);
    }
  });
}

function checkAch() {
  for (const a of ACH)
    if (!P.ach[a.id] && a.f()) {
      P.ach[a.id] = 1;
      addCoins(a.r);
      toast('Достижение: ' + a.t + ' +' + a.r);
    }
}

function dailyInit() {
  const t = todayKey();
  if (P.day === t)
    return;
  P.days = P.day === todayKey(new Date(Date.now() - 86400000)) ? P.days + 1 : 1;
  P.day = t;
  P.st.dayCount = (P.st.dayCount || 0) + 1;
  let h = 0;
  for (const c of t)
    h = (h * 31 + c.charCodeAt(0)) % 997;
  P.tasks = [0, 2, 4].map(k => ({
    i: (h + k) % TASKS.length,
    p: 0,
    done: false
  }));
  const b = Math.min(P.days, 7) * 3;
  addCoins(b);
  toast('Заход ' + P.days + ' дн. подряд: +' + b);
  saveP();
}
