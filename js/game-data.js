// Сила врага считается от «эталонного» героя того же уровня (с типичным снаряжением и навыками):
// обычный враг отнимает ~55% здоровья, босс — столько, что без зелий/хорошей игры не победить.
const stat = (L, boss) => {
  const f = Math.min(6, Math.max(0, (L - 1) / 8)), i = Math.floor(f), j = Math.min(6, i + 1), u = f - i, GT = k => GEAR.reduce((a, sl) => a + sl[i][k] + (sl[j][k] - sl[i][k]) * u, 0);
  const rh = (60 + 8 * L + GT('h')) * 1.15, ra = (8 + 1.5 * L + GT('a')) * 1.1, rd = GT('d') + L / 6;
  const def = Math.floor(L * 0.8 * (boss ? 1.1 : 1)), taps = boss ? 11 : L < 6 ? 4 : 5.5;
  const hp = Math.round(Math.max(20, ra * 1.18 - def) * taps), D = rh * (boss ? 1.15 : L < 6 ? 0.4 : 0.55) / taps / 1.12;
  return {
    hp,
    atk: Math.max(4, Math.round(D / (60 / (60 + rd)))),
    def
  };
};

const ENEMIES = [];
ZONES.forEach((z, zi) => [...z.m, z.b].forEach((m, k) => {
  const boss = k === 5, L = zi * 10 + (boss ? 10 : [1, 2, 4, 6, 8][k]);
  ENEMIES.push({
    i: ENEMIES.length,
    z: zi,
    boss,
    n: m[0],
    ic: m[1],
    lv: L,
    ...stat(L, boss),
    rc: Math.round((6 + L * 1.4) * (boss ? 4 : 1)),
    rx: Math.round((15 + L * 6) * (boss ? 3 : 1)),
    sz: boss ? 1.45 : 0.85 + k * 0.05
  });
}));

